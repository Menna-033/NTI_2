/* ????? ?????? Timer 0 ??? ????? ?????? Normal/Overflow Mode */
void TIMER0_voidInit(void) {
	/* ?????? Normal Mode: WGM00 = 0, WGM01 = 0 */
	clr_bit(TCCR0, WGM00);
	clr_bit(TCCR0, WGM01);

	/* ??? Prescaler = 1024: CS02 = 1, CS01 = 0, CS00 = 1 */
	set_bit(TCCR0, CS02);
	clr_bit(TCCR0, CS01);
	set_bit(TCCR0, CS00);
}

/* ???? ???????? ???????? ??? ???? ??? Overflow */
void TIMER0_voidSetDelayMs(u32 Copy_u32DelayMs) {
	u32 Local_u32OverflowCounter = 0;
	
	/* ???? ??? ??? Overflows ???????? ????? ?????? */
	u32 Local_u32MaxOverflows = (Copy_u32DelayMs * 1000UL) / 16384UL;

	while (Local_u32OverflowCounter < Local_u32MaxOverflows) {
		/* ???????? ??? ???? Overflow (?? TOV0 ???? 1) */
		while (get_bit(TIFR, TOV0) == 0);

		/* ??? ????? (Flag) ?????? 1 ???? */
		set_bit(TIFR, TOV0);

		Local_u32OverflowCounter++;
	}
}