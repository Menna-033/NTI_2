#define F_CPU 16000000UL
#include <util/delay.h>

#include "STD_TYPES.h"
#include "BIT_MATH.h"
#include "DIO.h"
#include "ADC4.h"

#define LIGHT_THRESHOLD  500

int main(void) {
	/* ????? ???? ??? ADC */
	ADC_voidInit();
	
	/* ??? ????? PC0 ????? ??? LED ???????? ?????? DIO ?????? ??? */
	DIO_voidSetPinDirection(DPORTC, PIN0, OUTPUT);
	
	u16 Local_u16AdcValue = 0;

	while (1) {
		/* ????? ???? ?????? ?? ?????? PA0 (Channel 0) */
		Local_u16AdcValue = ADC_u16ReadChannel(0);

		/* ?? ???? ?????? (????? ??? ADC ??? ?? 500) ??? ????? ??? LED */
		if (Local_u16AdcValue < LIGHT_THRESHOLD) {
			DIO_voidSetPinValue(DPORTC, PIN0, HIGH);
		}
		/* ?? ???? ????? ??? ????? ??? LED */
		else {
			DIO_voidSetPinValue(DPORTC, PIN0, LOW);
		}

		_delay_ms(100);
	}

	return 0;
}